def repo_types(cfg: dict) -> list:
    """The configurable repository types (id/name/color). Falls back to the
    built-in platform/app pair for configs written before types were open-ended."""
    types = cfg.get("repo_types")
    return list(types) if types else [dict(t) for t in _DEFAULT_REPO_TYPES]


def default_repo_type(cfg: dict) -> str:
    """The type unlisted repos fall into (the one flagged `default`, else the last)."""
    types = repo_types(cfg)
    for t in types:
        if t.get("default"):
            return t["id"]
    return types[-1]["id"] if types else "app"


def classify(name: str, cfg: dict) -> str:
    """Repo -> type id from the config's per-type repo lists; 'ignore' is always
    honoured; anything unlisted is 'unclassified' (resolves to the default type)."""
    ids = [t["id"] for t in repo_types(cfg)] + ["ignore"]
    repos = cfg.get("repos") or {}
    for cls in ids:
        if name in (repos.get(cls) or []):
            return cls
    return "unclassified"


def make_element(cfg: dict):
    """Repo name -> product element. Exact names win; then trailing-'*' prefix
    globs (e.g. 'example-core*'); else `elements.default`. Orthogonal to platform/app.
    Same mapping applies across both orgs because repo names mirror."""
    elems = cfg.get("elements", {}) or {}
    default = elems.get("default", "Other")
    exact: dict[str, str] = {}
    prefixes: list[tuple[str, str]] = []
    for elem, pats in elems.items():
        if elem == "default":
            continue
        for pat in (pats or []):
            if pat.endswith("*"):
                prefixes.append((pat[:-1], elem))
            else:
                exact[pat] = elem

    def element_of(name: str) -> str:
        if name in exact:
            return exact[name]
        for pre, elem in prefixes:
            if name.startswith(pre):
                return elem
        return default

    return element_of


def build_elements_rollup(repos: dict, people: dict, elements_ttm: dict) -> dict:
    """Aggregate per-element stats from repo meta + people. LOC sums skip
    non-cloned repos (code_loc/spec_loc None). people_* count distinct logins
    whose commit-repos fall in the element."""
    def _med(xs):
        return statistics.median(xs) if xs else None

    name2elem: dict[str, str] = {}
    roll: dict[str, dict] = {}
    for meta in repos.values():
        if meta.get("archived"):
            continue
        e = meta.get("element", "Other")
        name2elem[meta["name"]] = e
        r = roll.setdefault(e, {
            "element": e, "code_loc": 0, "spec_loc": 0, "repos": 0,
            "commits_window": 0, "ai_commits_window": 0,
            "prs_opened_window": 0, "prs_merged_window": 0,
            "people_members": 0, "people_external": 0, "median_ttm_h": None,
        })
        r["repos"] += 1
        r["code_loc"] += meta.get("code_loc") or 0
        r["spec_loc"] += meta.get("spec_loc") or 0
        r["commits_window"] += meta.get("commits_window", 0)
        r["ai_commits_window"] += meta.get("ai_commits_window", 0)
        r["prs_opened_window"] += meta.get("prs_opened_window", 0)
        r["prs_merged_window"] += meta.get("prs_merged_window", 0)

    elem_members: dict[str, set] = {}
    elem_external: dict[str, set] = {}
    for login, p in people.items():
        for repo_name in p.get("repos", []):
            e = name2elem.get(repo_name)
            if not e:
                continue
            bucket = elem_members if p.get("is_member") else elem_external
            bucket.setdefault(e, set()).add(login)
    for e, r in roll.items():
        r["people_members"] = len(elem_members.get(e, set()))
        r["people_external"] = len(elem_external.get(e, set()))
        r["ai_pct"] = round(100 * r["ai_commits_window"] / r["commits_window"], 1) if r["commits_window"] else 0.0
        r["median_ttm_h"] = _med(elements_ttm.get(e, []))
    return roll


def make_is_spec(spec_cfg: dict):
    exc_seg = {s.lower() for s in spec_cfg.get("exclude_segments", [])}
    exc_base = {b.lower() for b in spec_cfg.get("exclude_basenames", [])}
    exc_pref = tuple(p.lower() for p in spec_cfg.get("exclude_name_prefixes", []))

    def is_spec(path: str) -> bool:
        if not path.endswith(".md"):
            return False
        segs = [s.lower() for s in path.split("/")]
        if any(s in exc_seg for s in segs):
            return False
        base = segs[-1]
        return base not in exc_base and not base.startswith(exc_pref)

    return is_spec


def make_is_meaningful_loc(loc_cfg: dict):
    exc_seg = {s.lower() for s in loc_cfg.get("exclude_segments", [])}
    exc_base = {b.lower() for b in loc_cfg.get("exclude_basenames", [])}
    exc_pref = tuple(p.lower() for p in loc_cfg.get("exclude_name_prefixes", []))
    exc_suff = tuple(s.lower() for s in loc_cfg.get("exclude_suffixes", []))

    def is_meaningful(path: str) -> bool:
        low = path.lower()
        segs = low.split("/")
        base = segs[-1]
        if any(s in exc_seg for s in segs):
            return False
        if base in exc_base:
            return False
        if base.startswith(exc_pref):
            return False
        if low.endswith(exc_suff):
            return False
        return True

    return is_meaningful


CONV_TYPES = {"feat", "fix", "docs", "refactor", "test", "chore",
              "ci", "build", "perf", "style", "revert"}
CONV_RE = re.compile(r'^([a-z]+)(\([^)]*\))?!?:', re.I)


def commit_type(subject: str):
    """Conventional-commit type from a subject line, or None. Exact prefix parse."""
    m = CONV_RE.match(subject.strip())
    if m and m.group(1).lower() in CONV_TYPES:
        return m.group(1).lower()
    return None


def iso_week(s: str) -> str:
    """'2026-06-04T..' (Z or offset) -> 'YYYY-Www' ISO-week bucket."""
    try:
        dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        return "?"
    y, w, _ = dt.isocalendar()
    return f"{y}-W{w:02d}"


