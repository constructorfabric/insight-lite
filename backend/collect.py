def _pattern_of(val) -> str:
    return val.get("pattern", "") if isinstance(val, dict) else val


def _marker_spec(val):
    """Normalize a marker config value (str | dict) -> (pattern, paths, exclude)."""
    if isinstance(val, dict):
        return val.get("pattern", ""), val.get("paths") or [], val.get("exclude") or []
    return val, [], []


def scan_markers(dest: str, ref: str, markers: dict) -> dict:
    """git grep full content per marker -> {label: {files, lines, file_list}}.

    Requires a full (non-blobless) clone. Exit code 1 = no match (fine).
    Marker value may be a regex string or {pattern, paths, exclude}.
    """
    res = {}
    for label, val in markers.items():
        pat, paths, exclude = _marker_spec(val)
        pathspec = (["--", *paths, *[f":(exclude){e}" for e in exclude]]
                    if (paths or exclude) else [])
        out = subprocess.run(
            git_cmd(dest, "grep", "-I", "-E", "-n", "-e", pat, ref, *pathspec),
            capture_output=True, text=True,
        )
        if out.returncode > 1:
            res[label] = {"files": 0, "lines": 0, "file_list": []}
            continue
        files, lines = set(), 0
        for ln in out.stdout.splitlines():
            parts = ln.split(":", 3)  # ref:path:lineno:content
            if len(parts) >= 3:
                files.add(parts[1]); lines += 1
        res[label] = {"files": len(files), "lines": lines, "file_list": sorted(files)}
    return res


REVIEW_QUERY = """
query($owner:String!, $name:String!, $cursor:String) {
  repository(owner:$owner, name:$name) {
    pullRequests(first:50, after:$cursor, orderBy:{field:CREATED_AT, direction:DESC},
                 states:[MERGED, OPEN, CLOSED]) {
      pageInfo { hasNextPage endCursor }
      nodes { title number createdAt mergedAt author { login }
        reviews(first:30) { nodes { author { login } state submittedAt } }
        timelineItems(first:40, itemTypes:[REVIEW_REQUESTED_EVENT]) {
          nodes { ... on ReviewRequestedEvent { createdAt } } } } } } }
"""


def _hours_between(a: str, b: str) -> float:
    fa = datetime.fromisoformat(a.replace("Z", "+00:00"))
    fb = datetime.fromisoformat(b.replace("Z", "+00:00"))
    return round((fb - fa).total_seconds() / 3600, 1)


def gather_reviews(gh, org: str, name: str, since_iso: str, skip_prefixes: tuple = ()):
    """Per repo via GraphQL: reviewer votes, time-to-merge, review coverage.
    Migration-recreated PR stubs ('[PR #NNN] …') are skipped so they don't skew
    coverage % or median TTM (they're bulk-merged duplicates of originals).
    Returns (votes{login:{reviews,approvals}}, ttms[hours], total_prs, reviewed_prs)."""
    from collections import defaultdict
    votes = defaultdict(lambda: {"reviews": 0, "approvals": 0})
    author_ttms: dict = defaultdict(list)
    reviewer_lat: dict = defaultdict(list)   # login -> [hours request->approval]
    review_rows: list = []                   # granular per-review rows (period-queryable)
    ttms, total, reviewed = [], 0, 0
    cursor, pages = None, 0
    while pages < 60:
        pages += 1
        data = gh.graphql(REVIEW_QUERY, {"owner": org, "name": name, "cursor": cursor})
        prs = ((data.get("repository") or {}).get("pullRequests") or {})
        stop = False
        for pr in prs.get("nodes", []):
            if (pr.get("createdAt") or "") < since_iso:
                stop = True
                continue
            if skip_prefixes and (pr.get("title") or "").lstrip().startswith(skip_prefixes):
                continue                       # migration stub — not a real PR
            total += 1
            rvs = (pr.get("reviews") or {}).get("nodes", [])
            if rvs:
                reviewed += 1
            req_times = [t["createdAt"] for t in (pr.get("timelineItems") or {}).get("nodes", [])
                         if t.get("createdAt")]
            req0 = min(req_times) if req_times else pr.get("createdAt")
            for rv in rvs:
                a = (rv.get("author") or {}).get("login")
                if not a:
                    continue
                votes[a]["reviews"] += 1
                if rv.get("submittedAt"):
                    review_rows.append({"repo": f"{org}/{name}", "pr_number": pr.get("number"),
                                        "reviewer_login": a, "state": rv.get("state"),
                                        "submitted_at": rv["submittedAt"]})
                if rv.get("state") == "APPROVED":
                    votes[a]["approvals"] += 1
                    if req0 and rv.get("submittedAt"):
                        h = _hours_between(req0, rv["submittedAt"])
                        if h >= 0:
                            reviewer_lat[a].append(h)
            if pr.get("mergedAt"):
                h = _hours_between(pr["createdAt"], pr["mergedAt"])
                ttms.append(h)
                al = (pr.get("author") or {}).get("login")
                if al:
                    author_ttms[al].append(h)
        pi = prs.get("pageInfo", {})
        if stop or not pi.get("hasNextPage"):
            break
        cursor = pi["endCursor"]
    else:
        # page cap reached with more PRs available — older reviews/TTM missing
        gh.warnings.append(f"reviews {org}/{name}: truncated at {60 * 50} PRs")
        print(f"  WARN: reviews for {org}/{name} truncated at {60 * 50} PRs",
              file=sys.stderr)
    return votes, ttms, total, reviewed, author_ttms, reviewer_lat, review_rows


# --- issue/PR timeline events (retrospective flow signal) -------------------
# GraphQL __typename -> our compact event name. These lifecycle events DO carry
# historical timestamps (unlike Projects-v2 status), so flow is backfillable.
_TL_EVENT = {
    "ReadyForReviewEvent": "ready_for_review", "ConvertToDraftEvent": "convert_to_draft",
    "ReviewRequestedEvent": "review_requested", "ReopenedEvent": "reopened",
    "MergedEvent": "merged", "ClosedEvent": "closed", "AssignedEvent": "assigned",
}
# Inline fragments must only name types in the connection's union, or GraphQL
# rejects the query — so PR and issue timelines get their own fragment sets.
_TL_PR_FRAGMENT = """__typename
  ... on ReadyForReviewEvent{createdAt actor{login}}
  ... on ConvertToDraftEvent{createdAt actor{login}}
  ... on ReviewRequestedEvent{createdAt actor{login}}
  ... on ReopenedEvent{createdAt actor{login}}
  ... on MergedEvent{createdAt actor{login}}
  ... on ClosedEvent{createdAt actor{login}}
  ... on AssignedEvent{createdAt actor{login}}"""
_TL_ISSUE_FRAGMENT = """__typename
  ... on ReopenedEvent{createdAt actor{login}}
  ... on ClosedEvent{createdAt actor{login}}
  ... on AssignedEvent{createdAt actor{login}}"""
_TL_PR_QUERY = """
query($owner:String!,$name:String!,$cursor:String){ repository(owner:$owner,name:$name){
  pullRequests(first:50,after:$cursor,orderBy:{field:CREATED_AT,direction:DESC},states:[MERGED,OPEN,CLOSED]){
    pageInfo{hasNextPage endCursor}
    nodes{ number createdAt
      timelineItems(first:40,itemTypes:[READY_FOR_REVIEW_EVENT,CONVERT_TO_DRAFT_EVENT,REVIEW_REQUESTED_EVENT,REOPENED_EVENT,MERGED_EVENT,CLOSED_EVENT,ASSIGNED_EVENT]){
        nodes{ %s } } } } } }""" % _TL_PR_FRAGMENT
_TL_ISSUE_QUERY = """
query($owner:String!,$name:String!,$cursor:String){ repository(owner:$owner,name:$name){
  issues(first:50,after:$cursor,orderBy:{field:CREATED_AT,direction:DESC}){
    pageInfo{hasNextPage endCursor}
    nodes{ number createdAt
      timelineItems(first:40,itemTypes:[REOPENED_EVENT,CLOSED_EVENT,ASSIGNED_EVENT]){
        nodes{ %s } } } } } }""" % _TL_ISSUE_FRAGMENT


def gather_timeline_events(gh, org: str, name: str, since_iso: str, cap_pages: int = 60):
    """Per repo via GraphQL: the flow-relevant lifecycle events on PRs and issues
    created since `since_iso`. Returns rows for store.write_timeline_events()."""
    repo = f"{org}/{name}"
    rows: list = []
    for conn_key, query, itype in (("pullRequests", _TL_PR_QUERY, "pull_request"),
                                   ("issues", _TL_ISSUE_QUERY, "issue")):
        cursor, pages = None, 0
        while pages < cap_pages:
            pages += 1
            data = gh.graphql(query, {"owner": org, "name": name, "cursor": cursor})
            conn_data = (data.get("repository") or {}).get(conn_key) or {}
            stop = False
            for node in conn_data.get("nodes", []):
                if (node.get("createdAt") or "") < since_iso:
                    stop = True
                    continue
                num = node.get("number")
                for ev in (node.get("timelineItems") or {}).get("nodes", []):
                    name_ = _TL_EVENT.get(ev.get("__typename"))
                    if not name_ or not ev.get("createdAt"):
                        continue
                    rows.append({"repo": repo, "item_type": itype, "number": num,
                                 "event": name_, "actor_login": (ev.get("actor") or {}).get("login") or "",
                                 "created_at": ev["createdAt"]})
            pi = conn_data.get("pageInfo", {})
            if stop or not pi.get("hasNextPage"):
                break
            cursor = pi["endCursor"]
    return rows


