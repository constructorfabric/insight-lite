def gather_project_status(gh, orgs):
    """Snapshot every org project's items + current Status AND all other board fields.
    Returns (status_rows, field_rows). Best-effort: a missing Projects permission or an
    org without boards just yields fewer rows."""
    status_rows, field_rows = [], []
    for org in orgs:
        d = gh.graphql(_PROJ_LIST_Q, {"login": org})
        projects = (((d or {}).get("organization") or {}).get("projectsV2") or {}).get("nodes", [])
        for pr in projects:
            num = pr.get("number")
            if num is None:
                continue
            cursor = None
            while True:
                dd = gh.graphql(_PROJ_ITEMS_Q, {"login": org, "num": num, "cursor": cursor})
                pv = ((dd or {}).get("organization") or {}).get("projectV2") or {}
                items = pv.get("items") or {}
                nodes = items.get("nodes", [])
                status_rows += _parse_project_items(org, num, nodes)
                field_rows += _parse_project_fields(org, num, nodes)
                page = items.get("pageInfo") or {}
                cursor = page.get("endCursor")
                if not page.get("hasNextPage") or not cursor:
                    break
    return status_rows, field_rows


# --- CI runs (GitHub Actions) ----------------------------------------------
# RAW capture of workflow runs in the collection window. Which workflow is a
# "gate" vs "nightly" and what counts as green are semantic-config derivations,
# so we store every run untouched. Bounded by created:>=since + a per-repo cap
# because busy repos accrue tens of thousands of runs (observed 31k+).
def _parse_ci_runs(repo: str, runs) -> list:
    """Actions workflow_runs[] -> raw ci_run rows (pure; unit-tested)."""
    out = []
    for r in runs or []:
        started, updated = r.get("run_started_at"), r.get("updated_at")
        duration = None
        if started and updated and r.get("status") == "completed":
            try:
                secs = int((datetime.fromisoformat(updated.replace("Z", "+00:00"))
                            - datetime.fromisoformat(started.replace("Z", "+00:00"))).total_seconds())
                duration = secs if secs >= 0 else None
            except ValueError:
                duration = None
        out.append({
            "repo": repo, "run_id": r.get("id"), "workflow": r.get("name"),
            "event": r.get("event"), "branch": r.get("head_branch"),
            "status": r.get("status"), "conclusion": r.get("conclusion"),
            "created_at": r.get("created_at"), "run_started_at": started,
            "updated_at": updated, "duration_s": duration,
            "head_sha": r.get("head_sha"), "actor": (r.get("actor") or {}).get("login"),
        })
    return out


def gather_ci_runs(gh, repos, since_date: str, cap: int = 1500) -> list:
    """Workflow runs created since `since_date` for each repo (page-walked with a
    per-repo cap). Repos without Actions just return nothing."""
    rows = []
    for full in repos:
        got, page = 0, 1
        while got < cap:
            sc, body = gh.get_json(f"/repos/{full}/actions/runs",
                                   {"created": f">={since_date}", "per_page": 100, "page": page})
            if sc != 200 or not isinstance(body, dict):
                break
            runs = body.get("workflow_runs") or []
            if not runs:
                break
            rows += _parse_ci_runs(full, runs)
            got += len(runs)
            if len(runs) < 100:
                break
            page += 1
    return rows


# --- issue raw enrichment (native type + labels + lifecycle) ----------------
# The REST search pass finds WHICH issues are in the window; only GraphQL exposes
# the native Issue Type and the full label set / lifecycle. This pass fetches
# those raw fields per repo and is merged into the existing issue rows by
# (repo, number) — it never adds or drops rows, only enriches. Best-effort: a
# repo the token can't read Issue Types on just yields no enrichment for that repo.
_ISSUE_ENRICH_Q = (
    "query($owner:String!,$name:String!,$since:DateTime!,$cursor:String){"
    "repository(owner:$owner,name:$name){issues(first:100, after:$cursor, "
    "filterBy:{since:$since}, orderBy:{field:UPDATED_AT,direction:DESC}){"
    "pageInfo{hasNextPage endCursor} nodes{number issueType{name} state "
    "stateReason closedAt milestone{title} "
    "labels(first:20){nodes{name}} assignees(first:10){nodes{login}}}}}}")


def _parse_issue_enrichment(owner: str, name: str, nodes) -> dict:
    """Issue nodes -> {(repo, number): raw enrichment fields} (pure; unit-tested)."""
    repo = f"{owner}/{name}"
    out = {}
    for it in nodes or []:
        num = it.get("number")
        if num is None:
            continue
        out[(repo, num)] = {
            "issue_type": (it.get("issueType") or {}).get("name") or "",
            "labels": [l["name"] for l in (it.get("labels") or {}).get("nodes", [])],
            "state": it.get("state") or "",
            "state_reason": it.get("stateReason") or "",
            "closed_at": it.get("closedAt") or "",
            "assignees": [a["login"] for a in (it.get("assignees") or {}).get("nodes", [])],
            "milestone": (it.get("milestone") or {}).get("title") or "",
        }
    return out


def gather_issue_enrichment(gh, repos, since_iso: str, cap_pages: int = 40) -> dict:
    """Per-repo GraphQL enrichment for issues updated since `since_iso`."""
    enrich = {}
    for full in repos:
        owner, _, name = full.partition("/")
        cursor, pages = None, 0
        while pages < cap_pages:
            d = gh.graphql(_ISSUE_ENRICH_Q,
                           {"owner": owner, "name": name, "since": since_iso, "cursor": cursor})
            issues = ((d or {}).get("repository") or {}).get("issues") or {}
            enrich.update(_parse_issue_enrichment(owner, name, issues.get("nodes", [])))
            page = issues.get("pageInfo") or {}
            cursor = page.get("endCursor")
            if not page.get("hasNextPage") or not cursor:
                break
            pages += 1
    return enrich


# --- PR raw enrichment (size, lifecycle, review/comment counts, reverts) ----
# The search pass finds which PRs are in the window; GraphQL adds size, the
# OPEN/CLOSED/MERGED state (closed-unmerged = abandoned), engagement counts,
# author association, linked-issue count and a revert flag. Merged into existing
# PR rows by (repo, number); never adds/drops rows. PRs have no `since` filter, so
# we page by UPDATED_AT desc and stop once past the window.
_PR_ENRICH_Q = (
    "query($owner:String!,$name:String!,$cursor:String){"
    "repository(owner:$owner,name:$name){pullRequests(first:100, after:$cursor, "
    "orderBy:{field:UPDATED_AT,direction:DESC}){pageInfo{hasNextPage endCursor} "
    "nodes{number title state closedAt additions deletions changedFiles "
    "authorAssociation isDraft updatedAt reviews{totalCount} comments{totalCount} "
    "closingIssuesReferences{totalCount} labels(first:20){nodes{name}}}}}}")


def _parse_pr_enrichment(owner: str, name: str, nodes) -> dict:
    """PR nodes -> {(repo, number): raw enrichment fields} (pure; unit-tested)."""
    repo = f"{owner}/{name}"
    out = {}
    for pr in nodes or []:
        num = pr.get("number")
        if num is None:
            continue
        title = pr.get("title") or ""
        out[(repo, num)] = {
            "state": pr.get("state") or "",
            "closed_at": pr.get("closedAt") or "",
            "additions": pr.get("additions"),
            "deletions": pr.get("deletions"),
            "changed_files": pr.get("changedFiles"),
            "review_count": (pr.get("reviews") or {}).get("totalCount"),
            "comment_count": (pr.get("comments") or {}).get("totalCount"),
            "author_association": pr.get("authorAssociation") or "",
            "closes_issues": (pr.get("closingIssuesReferences") or {}).get("totalCount"),
            "is_revert": 1 if title.lower().startswith("revert") else 0,
            "is_draft": 1 if pr.get("isDraft") else 0,
            "labels": [l["name"] for l in (pr.get("labels") or {}).get("nodes", [])],
            "title": title,
        }
    return out


def gather_pr_enrichment(gh, repos, since_iso: str, cap_pages: int = 40) -> dict:
    """Per-repo GraphQL PR enrichment, paged by UPDATED_AT desc until past the window."""
    enrich = {}
    for full in repos:
        owner, _, name = full.partition("/")
        cursor, pages = None, 0
        while pages < cap_pages:
            d = gh.graphql(_PR_ENRICH_Q, {"owner": owner, "name": name, "cursor": cursor})
            prs = ((d or {}).get("repository") or {}).get("pullRequests") or {}
            nodes = prs.get("nodes", [])
            enrich.update(_parse_pr_enrichment(owner, name, nodes))
            oldest = nodes[-1].get("updatedAt") if nodes else None
            page = prs.get("pageInfo") or {}
            if (oldest and oldest < since_iso) or not page.get("hasNextPage") \
                    or not page.get("endCursor"):
                break
            cursor = page["endCursor"]
            pages += 1
    return enrich


def scan_tracker(dest: str, ref: str, markers: dict) -> dict:
    """Generic tracker scan: each marker is content (git grep) or files (ls-tree)
    by its `mode`. Returns {label: {files, lines}}."""
    res = {}
    tree_cache = None
    for label, val in markers.items():
        mode = val.get("mode", "content") if isinstance(val, dict) else "content"
        pat, _, _ = _marker_spec(val)
        if mode == "files":
            nonlocal_tree = tree_cache
            if nonlocal_tree is None:
                nonlocal_tree = subprocess.run(
                    git_cmd(dest, "ls-tree", "-r", "--name-only", ref),
                    capture_output=True, text=True).stdout.splitlines()
                tree_cache = nonlocal_tree
            rx = re.compile(pat)
            n = sum(1 for p in nonlocal_tree if rx.search(p))
            res[label] = {"files": n, "lines": n}
        else:
            sc = scan_markers(dest, ref, {label: val})[label]
            res[label] = {"files": sc["files"], "lines": sc["lines"]}
    return res


def blame_marker_authors(dest: str, ref: str, pattern: str, files: list) -> Counter:
    """For each marker-matching line in `files`, blame its author email.
    Returns Counter(author_email -> marker-line count). Needs full history."""
    rx = re.compile(pattern)
    votes: Counter = Counter()
    for f in files:
        out = subprocess.run(
            git_cmd(dest, "blame", "--line-porcelain", ref, "--", f),
            capture_output=True, text=True,
        )
        if out.returncode != 0:
            continue
        cur_mail = None
        for ln in out.stdout.split("\n"):
            if ln.startswith("author-mail "):
                cur_mail = ln[12:].strip().strip("<>").lower()
            elif ln.startswith("\t"):
                if cur_mail and rx.search(ln[1:]):
                    votes[cur_mail] += 1
    return votes


def _blame_file_records(dest: str, ref: str, path: str, is_spec_file: bool) -> dict[str, int]:
    """Blame one file. Returns {f'{email}{F}{kind}{F}{ai}{F}{date}': count}
    where kind in {code,spec}, ai in {0,1}, date = committer-date YYYY-MM-DD.
    Origin: lines inside @cpt-begin/@cpt-end (inclusive) or @cpt-...: are AI; a
    file with `studio: true` frontmatter or a `Generated by cf/cfs` stamp is
    wholly AI. Needs a full (with-blobs) clone."""
    # errors="replace": blamed source files can contain non-UTF-8 bytes (latin-1,
    # binary-ish content git didn't treat as binary); lossy decode is fine since
    # we only count lines and match ASCII markers.
    out = subprocess.run(
        git_cmd(dest, "blame", "--line-porcelain", ref, "--", path),
        capture_output=True, text=True, errors="replace",
    )
    if out.returncode != 0:
        return {}
    kind = "spec" if is_spec_file else "code"
    # Parse porcelain into ordered per-line records: (email, date, content)
    lines: list[tuple[str, str, str]] = []
    cur_mail, cur_date = None, "0000-00-00"
    for ln in out.stdout.split("\n"):
        if ln.startswith("author-mail "):
            cur_mail = ln[12:].strip().strip("<>").lower()
        elif ln.startswith("committer-time "):
            try:
                cur_date = datetime.fromtimestamp(
                    int(ln[15:].strip()), tz=timezone.utc).strftime("%Y-%m-%d")
            except ValueError:
                cur_date = "0000-00-00"
        elif ln.startswith("\t"):
            lines.append((cur_mail or "", cur_date, ln[1:]))
    content = "\n".join(t for _, _, t in lines)
    whole_ai = bool(GEN_STAMP.search(content)) or (is_spec_file and STUDIO_SPEC.search(content))
    counts: Counter = Counter()
    in_cpt = False
    for email, date, text in lines:
        # CPT_BEGIN/CPT_END must precede CPT_SINGLE: a "@cpt-begin:" line is a region bound, not a single marker.
        if whole_ai:
            ai = 1
        elif CPT_BEGIN.search(text):
            in_cpt, ai = True, 1
        elif CPT_END.search(text):
            ai, in_cpt = 1, False
        elif CPT_SINGLE.search(text):
            ai = 1
        else:
            ai = 1 if in_cpt else 0
        counts[f"{email}{F}{kind}{F}{ai}{F}{date}"] += 1
    return dict(counts)


def blame_tree(dest: str, ref: str, is_spec, is_meaningful_loc,
               since_date: str, cache: dict):
    """Blame every spec/code file in `ref`'s tree -> surviving-LOC per author.

    Returns (acc, sizes, cache):
      acc[email] = {code_human, code_ai, spec_human, spec_ai,
                    win_code_human, win_code_ai, win_spec_human, win_spec_ai}
        all-time = every surviving line; win_* = lines whose committer-date >= since_date.
      sizes = {code_loc, spec_loc, total_loc}  (totals across all authors)
      cache = {f'{path}\x00{blob_sha}': records}  reusable across runs;
        unchanged blobs are read from cache instead of re-blamed.
    Spec precedence: a spec .md is counted as spec, never code."""
    tree = subprocess.run(
        git_cmd(dest, "ls-tree", "-r", ref),
        capture_output=True, text=True, errors="replace",
    )
    acc: dict[str, dict] = {}
    sizes = {"code_loc": 0, "spec_loc": 0, "total_loc": 0}
    if tree.returncode != 0:
        print(f"  ls-tree failed: {os.path.basename(dest)}: {git_error(tree, '')}", file=sys.stderr)
        return acc, sizes, cache

    def slot(email: str) -> dict:
        return acc.setdefault(email, {
            "code_human": 0, "code_ai": 0, "spec_human": 0, "spec_ai": 0,
            "win_code_human": 0, "win_code_ai": 0, "win_spec_human": 0, "win_spec_ai": 0,
        })

    for row in tree.stdout.splitlines():
        # "<mode> <type> <sha>\t<path>"
        meta, _, path = row.partition("\t")
        parts = meta.split()
        if len(parts) != 3 or parts[1] != "blob":
            continue
        blob = parts[2]
        is_spec_file = is_spec(path)
        if not is_spec_file and not is_meaningful_loc(path):
            continue
        key = f"{path}{NUL}{blob}"
        records = cache.get(key)
        if records is None:
            records = _blame_file_records(dest, ref, path, is_spec_file)
            cache[key] = records
        for ckey, n in records.items():
            email, kind, ai, date = ckey.split(F)
            origin = "ai" if ai == "1" else "human"
            s = slot(email)
            s[f"{kind}_{origin}"] += n
            sizes[f"{kind}_loc"] += n
            sizes["total_loc"] += n
            if date >= since_date:
                s[f"win_{kind}_{origin}"] += n
    return acc, sizes, cache


def detect_ai_map(dest: str, since_iso: str, detector, ref: str) -> dict:
    """sha -> [tool names] for commits whose message matches a marker."""
    if not detector:
        return {}
    out = subprocess.run(
        git_cmd(dest, "log", ref, "--no-merges", f"--since={since_iso}",
                "--pretty=%H%x1e%B%x1f"),
        capture_output=True, text=True,
    ).stdout
    m = {}
    for chunk in out.split("\x1f"):
        if "\x1e" not in chunk:
            continue
        sha, body = chunk.split("\x1e", 1)
        tools = [n for n, rx in detector if rx.search(body)]
        if tools:
            m[sha.strip()] = tools
    return m


def _utc_z(iso: str) -> str:
    """Author date (%aI, has a tz offset) -> UTC 'YYYY-MM-DDTHH:MM:SSZ' so all
    date columns are one comparable format for range queries."""
    try:
        return (datetime.fromisoformat(iso).astimezone(timezone.utc)
                .strftime("%Y-%m-%dT%H:%M:%SZ"))
    except ValueError:
        return iso


def parse_git(dest: str, since_iso: str, is_spec, classification: str,
              email_agg: dict, email_names: dict, contributors: set,
              weekly: dict, is_meaningful_loc=None, ai_map=None, repo_types=None,
              repo_acc=None, commit_sink: list | None = None, repo_key: str | None = None) -> None:
    """One git-log pass: per author-email tally commits, LOC, spec-edits, names,
    weekly buckets, and AI-tool attribution (commits + meaningful LOC per tool).
    If `commit_sink` is given, also append one granular per-commit row to it
    (author_login resolved later, by the caller)."""
    ai_map = ai_map or {}
    fmt = f"{C}%H{F}%ae{F}%an{F}%aI{F}%s"
    out = subprocess.run(
        git_cmd(dest, "log", "--no-merges", f"--since={since_iso}",
                f"--pretty=tformat:{fmt}", "--numstat", log_ref(dest)),
        capture_output=True, text=True,
    )
    if out.returncode != 0:
        print(f"  git log failed: {os.path.basename(dest)}: {git_error(out, '')}", file=sys.stderr)
        return
    cur_email = None
    cur_week = "?"
    cur_spec = False
    cur_tools: list = []
    cur_meaningful = 0
    cur_sha = cur_date = cur_type = None
    cur_subject = ""
    cur_add = cur_del = cur_mdel = 0           # per-commit raw/meaningful tallies
    repo = os.path.basename(dest)
    rkey = repo_key or repo

    def agg(email):
        return email_agg.setdefault(email, {
            "commits": 0, "additions": 0, "deletions": 0,
            "meaningful_additions": 0, "meaningful_deletions": 0,
            "platform_commits": 0, "app_commits": 0, "specs": 0, "repos": set(),
            "platform_meaningful": 0, "app_meaningful": 0,
            "ai_commits": 0, "ai_loc": 0, "ai": {}, "types": {},
        })

    def flush():
        if not cur_email:
            return
        if cur_spec:
            agg(cur_email)["specs"] += 1
            bump(weekly, "specs", cur_week)
        if cur_tools:
            a = agg(cur_email)
            a["ai_commits"] += 1
            a["ai_loc"] += cur_meaningful
            if repo_acc is not None:
                repo_acc["ai_commits"] = repo_acc.get("ai_commits", 0) + 1
            for t in cur_tools:
                d = a["ai"].setdefault(t, {"commits": 0, "loc": 0})
                d["commits"] += 1
                d["loc"] += cur_meaningful
        if commit_sink is not None and cur_sha:
            commit_sink.append({
                "repo": rkey, "sha": cur_sha, "committed_at": _utc_z(cur_date),
                "author_email": cur_email, "classification": classification,
                "additions": cur_add, "deletions": cur_del,
                "meaningful_additions": cur_meaningful, "meaningful_deletions": cur_mdel,
                "is_spec": 1 if cur_spec else 0, "commit_type": cur_type,
                "ai_marked": 1 if cur_tools else 0,
                "ai_loc": cur_meaningful if cur_tools else 0,
                "ai_tools": ",".join(sorted(cur_tools)) if cur_tools else "",
                "title": cur_subject,
            })

    for line in out.stdout.splitlines():
        if line.startswith(C):
            flush()
            parts = line[1:].split(F)
            sha, email, name, date = parts[0], parts[1], parts[2], parts[3]
            subject = parts[4] if len(parts) > 4 else ""
            email = email.lower()
            a = agg(email)
            a["commits"] += 1
            if repo_acc is not None:
                repo_acc["commits"] = repo_acc.get("commits", 0) + 1
            a[f"{classification}_commits"] += 1
            a["repos"].add(repo)
            # every commit gets a bucket; non-conventional subjects -> "other"
            # so the Work-type breakdown sums to the total commit count.
            ct = commit_type(subject) or "other"
            a["types"][ct] = a["types"].get(ct, 0) + 1
            if repo_types is not None:
                rt = repo_types.setdefault(repo, {})
                rt[ct] = rt.get(ct, 0) + 1
            email_names.setdefault(email, set()).add(name.strip())
            contributors.add(email)
            cur_email, cur_week, cur_spec = email, iso_week(date), False
            cur_tools, cur_meaningful = ai_map.get(sha, []), 0
            cur_sha, cur_date, cur_type = sha, date, ct
            cur_subject = subject
            cur_add = cur_del = cur_mdel = 0
            bump(weekly, "commits", cur_week)
        elif line.strip() and cur_email:
            parts = line.split("\t")
            if len(parts) != 3:
                continue
            add, dele, path = parts
            a = email_agg[cur_email]
            if add.isdigit():
                a["additions"] += int(add)
                cur_add += int(add)
            if dele.isdigit():
                a["deletions"] += int(dele)
                cur_del += int(dele)
            if is_meaningful_loc is None or is_meaningful_loc(path):
                if add.isdigit():
                    a["meaningful_additions"] += int(add)
                    a[f"{classification}_meaningful"] += int(add)
                    cur_meaningful += int(add)
                if dele.isdigit():
                    a["meaningful_deletions"] += int(dele)
                    cur_mdel += int(dele)
            if is_spec(path):
                cur_spec = True
    flush()


def merge_traffic_history(conn, repos: dict) -> int:
    """Accumulate RAW per-repo/per-day traffic into the SQLite store.

    GitHub's Traffic API only returns the trailing 14 days, so anything older
    is UNRECOVERABLE once it ages out — unlike commits/LOC, which always live in
    the clones. Running the collector at least every 14 days builds a gap-free
    daily history. Keyed by (repo, date); the latest run wins (a day seen while
    still in progress is partial — a later run completes it)."""
    rows = []
    for key, meta in repos.items():
        if not meta.get("traffic_access"):
            continue
        daily_c = {x["date"]: x for x in meta.get("clones_daily", [])}
        daily_v = {x["date"]: x for x in meta.get("views_daily", [])}
        # views may have failed even though clones succeeded — write NULL for the
        # view columns so upsert PRESERVES stored history instead of zeroing it.
        views_ok = meta.get("views_ok", False)
        for date in sorted(set(daily_c) | set(daily_v)):
            c, v = daily_c.get(date, {}), daily_v.get(date, {})
            rows.append({
                "repo": key, "date": date,
                "clones": c.get("count", 0), "clone_uniques": c.get("uniques", 0),
                "views": (v.get("count", 0) if views_ok else None),
                "view_uniques": (v.get("uniques", 0) if views_ok else None),
            })
    total = store.upsert_traffic(conn, rows) if rows else \
        conn.execute("SELECT COUNT(*) FROM traffic").fetchone()[0]
    days = conn.execute("SELECT COUNT(DISTINCT date) FROM traffic").fetchone()[0]
    print(f"Traffic history -> SQLite ({total} repo-day rows over {days} days; "
          f"{len(rows)} refreshed this run)", file=sys.stderr)
    return total


def apply_issue_taxonomy(conn, people: dict) -> int:
    """Materialize is_bug/is_feature/is_epic on every issue row from the ONE resolver
    (semantic.categorize_issue), then refresh the per-person issue counts in the run
    blob from those columns, so the all-time block matches what the window view reads
    live. Returns the number of issue rows recategorised.

    Raises on failure — unlike the enrichment / project-status / CI steps around it,
    this one is NOT best-effort. write_issues() has just replaced every in-window row
    with is_bug/is_feature/is_epic = 0, so this call is the *only* thing that puts a
    category on an issue. Swallowing the error (as a `WARN:` print did until now)
    ships a report stating zero Bugs, zero Features and zero Epics, with the only
    trace a line in a nightly log nobody reads. A run that dies is debuggable; a run
    that confidently reports zeros is not.
    """
    import semantic_metrics
    n = semantic_metrics.recategorize_issues(conn)
    for r in conn.execute(
            "SELECT author_login login, SUM(is_bug) bugs, "
            "SUM(is_feature) features, SUM(is_epic) epics FROM issue "
            "WHERE is_bot=0 AND is_migration=0 AND author_login<>'' "
            "GROUP BY author_login"):
        p = people.get(r["login"])
        if p is not None:
            p["bugs"] = r["bugs"] or 0
            p["features"] = r["features"] or 0
            p["epics"] = r["epics"] or 0
    return n


def write_snapshot(conn, out: dict, people: dict) -> None:
    """Store one compact daily snapshot so the report can show contribution
    TRENDS over time (the window is a single point; accumulating snapshots is how
    dynamics become visible). Idempotent per day — a same-day re-run replaces it."""
    by_company: dict = {}
    for p in people.values():
        if p.get("total_activity", 0) <= 0:
            continue
        c = by_company.setdefault(p.get("company", "Other"),
                                  {"commits": 0, "meaningful_additions": 0,
                                   "prs": 0, "people": 0, "ai_commits": 0})
        c["commits"] += p["commits"]
        c["meaningful_additions"] += p.get("meaningful_additions", 0)
        c["prs"] += p["prs_opened"]
        c["people"] += 1
        c["ai_commits"] += p.get("ai_commits", 0)
    snap = {
        "date": out["generated_at"][:10], "generated_at": out["generated_at"],
        "lookback_days": out["lookback_days"],
        "totals": {
            "commits": sum(p["commits"] for p in people.values()),
            "meaningful_additions": sum(p.get("meaningful_additions", 0) for p in people.values()),
            "prs": sum(p["prs_opened"] for p in people.values()),
            "specs": sum(p["specs"] for p in people.values()),
            "people": sum(1 for p in people.values() if p.get("total_activity", 0) > 0),
            "ai_commits": sum(p.get("ai_commits", 0) for p in people.values()),
        },
        "by_company": by_company,
    }
    n = store.upsert_snapshot(conn, snap)
    print(f"Snapshot saved -> SQLite ({n} dated points)", file=sys.stderr)


def snapshot_status_only() -> int:
    """Lightweight, quota-cheap Projects-v2 status snapshot ONLY — no git, no PR/issue
    enrichment. Meant to run every few hours (cron) so the board CFD and the
    "returned to dev" rewinds catch intra-day moves the once-a-day full collect misses.

    Bypasses the API cache (NO_CACHE) so each run reads the board's live state rather
    than a cached morning copy, and is idempotent per exact timestamp. Cheap on quota:
    one project-list + a few item pages per org (~tens of GraphQL points)."""
    os.environ["NO_CACHE"] = "1"          # a point-in-time read must not be cached
    cfg = load_config()
    gh = GH(token(), cache_ttl_hours=0,
            max_wait_seconds=float(cfg.get("api_max_wait_seconds", 90)))
    orgs = [cfg["org"]] + (cfg.get("extra_orgs", []) or [])
    wis, wif = gather_project_status(gh, orgs)
    taken_at = datetime.now(timezone.utc).replace(microsecond=0).strftime("%Y-%m-%dT%H:%M:%SZ")
    db = store.connect()
    try:
        n = store.write_work_item_status(db, taken_at, wis) if wis else 0
        nf = store.write_work_item_fields(db, taken_at, wif) if wif else 0
    finally:
        db.close()
    if gh.rate_limited or gh.degraded:
        print(f"  WARN: snapshot degraded/rate-limited ({'; '.join(gh.degraded[:2])})",
              file=sys.stderr)
    print(f"Project status snapshot @ {taken_at}: {n} items, {nf} field-values -> SQLite",
          file=sys.stderr)
    return n


