def _field_value(fv: dict):
    """A single ProjectV2 field value node -> its scalar as text (or None)."""
    t = fv.get("__typename")
    if t == "ProjectV2ItemFieldSingleSelectValue":
        return fv.get("name")
    if t == "ProjectV2ItemFieldNumberValue":
        n = fv.get("number")
        if n is None:
            return None
        return str(int(n)) if float(n).is_integer() else str(n)
    if t == "ProjectV2ItemFieldTextValue":
        return fv.get("text")
    if t == "ProjectV2ItemFieldDateValue":
        return fv.get("date")
    if t == "ProjectV2ItemFieldIterationValue":
        return fv.get("title")
    return None


def _parse_project_fields(org: str, project_number, nodes) -> list:
    """ProjectV2 item nodes -> raw board-field rows (pure; unit-tested). One row per
    (item, field) with a non-empty value; built-in/duplicate fields skipped."""
    project = f"{org}/{project_number}"
    out = []
    for it in nodes or []:
        content = it.get("content") or {}
        repo = (content.get("repository") or {}).get("nameWithOwner")
        base = {"item_id": it.get("id"), "project": project, "repo": repo,
                "number": content.get("number")}
        for fv in ((it.get("fieldValues") or {}).get("nodes") or []):
            fname = ((fv.get("field") or {}).get("name") or "").strip()
            if not fname or fname in _PROJ_FIELD_SKIP:
                continue
            val = _field_value(fv)
            if val in (None, ""):
                continue
            out.append({**base, "field": fname, "value": val})
    return out


