def is_bot(login: str, bot_logins: list[str]) -> bool:
    low = (login or "").lower()
    for b in bot_logins:
        bl = b.lower()
        if bl.startswith("="):          # exact match (avoids e.g. "claude" hitting "claudette")
            if low == bl[1:]:
                return True
        elif bl in low:                 # substring match (default)
            return True
    return False


