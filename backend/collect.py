def load_directory() -> tuple[dict, dict, dict, dict]:
    """Identity overrides -> (email->login, login->company, login->name, alias->primary).

    `aliases: [other-login, …]` on an entry folds those logins INTO this one — so
    a merge in the editor sticks even for accounts whose activity is login-based
    (PRs/issues/reviews), not just commit-email-based."""
    ppl = load_person_overrides()
    email2login, login2co, login2name, alias2primary = {}, {}, {}, {}
    for login, info in ppl.items():
        info = info or {}
        if info.get("company"):
            login2co[login] = info["company"]
        if info.get("name"):
            login2name[login] = info["name"]
        for e in info.get("emails", []) or []:
            email2login[e.lower()] = login
        for alias in info.get("aliases", []) or []:
            alias2primary[alias] = login
    return email2login, login2co, login2name, alias2primary


